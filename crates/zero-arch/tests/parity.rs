//! The parity audit against the real documents (T-PAR-03). Every item in
//! `features.md` Parts 1, 2, and 8 must have exactly one assessed row, and the
//! generated page must match the data.

use std::path::{Path, PathBuf};

fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn data() -> String {
    std::fs::read_to_string(root().join("crates/zero-arch/data/parity.json")).unwrap()
}

#[test]
fn real_features_and_parity_data_are_ok() {
    let features = std::fs::read_to_string(root().join("features.md")).unwrap();
    let report = zero_arch::parity::check(&features, &data());
    assert!(report.ok, "{:#?}", report.errors);
    assert!(report.unassessed.is_empty());
    assert!(report.unknown.is_empty());
    assert!(report.missing.is_empty());
    assert!(report.duplicates.is_empty());
    assert!(report.empty_reasons.is_empty());
    assert!(report.implemented_without_refs.is_empty());
    assert_eq!(report.items, 133, "Part 1, 2, and 8 item count");
    assert_eq!(report.rows.len(), report.items);
    for (part, expected) in [(1u8, 49usize), (2, 42), (8, 42)] {
        assert_eq!(
            report.rows.iter().filter(|r| r.part == part).count(),
            expected,
            "Part {part} item count"
        );
    }
    assert_eq!(
        report.state_count(zero_arch::parity::State::Unassessed),
        0,
        "no row may be unassessed"
    );
}

#[test]
fn parity_page_is_generated_and_current() {
    let features = std::fs::read_to_string(root().join("features.md")).unwrap();
    let report = zero_arch::parity::check(&features, &data());
    assert!(report.ok, "{:#?}", report.errors);
    let expected = zero_arch::parity::render_markdown(&report);
    let actual = std::fs::read_to_string(root().join("docs/parity.md")).unwrap();
    assert_eq!(
        actual, expected,
        "docs/parity.md is stale; run `cargo run -p xtask -- parity-doc --write`"
    );
    assert!(actual.starts_with("# Parity audit\n\nGenerated by"));
}
